-- Fixy Barrio B1 (contrato BARRIO_B1_CONTRATO.md, 2026-10-27): reclamos vecinales públicos
-- (bache / restos de poda / luminaria apagada) con foto + ubicación, moderados por ops y
-- publicados en un mapa. Tablas PROPIAS, no `leads`: los schedulers de leads (matching,
-- reengagement, cierre, métricas) mandarían mensajes de técnico a estos vecinos.
-- Mismo criterio que V28–V33: CREATE ... IF NOT EXISTS (idempotente), sin FK (el jar anterior
-- no conoce estas tablas: rollback-safe), sin JSONB. En dev/test flyway está OFF y ddl-auto
-- cubre las entidades BarrioReport / BarrioClosureClaim / BarrioWaDraft; esta migración no
-- corre ahí pero se mantiene sincronizada con ellas.
--
-- description y reporter_phone son PRIVADOS (solo ops): ningún endpoint público los devuelve.

CREATE TABLE IF NOT EXISTS barrio_reports (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category varchar(16) NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'PENDING_REVIEW',
  lat double precision NOT NULL,
  lng double precision NOT NULL,
  zone varchar(80) NOT NULL DEFAULT 'Ciudad de la Costa',
  photo_path varchar(255) NOT NULL,
  description varchar(500) NULL,
  reporter_phone varchar(30) NULL,
  channel varchar(12) NOT NULL DEFAULT 'web',
  supporters integer NOT NULL DEFAULT 1,
  merged_into_id bigint NULL,
  reject_reason varchar(300) NULL,
  created_at timestamp(6) with time zone NOT NULL,
  published_at timestamp(6) with time zone NULL,
  resolved_at timestamp(6) with time zone NULL,
  days_to_resolve integer NULL,
  closure_photo_path varchar(255) NULL,
  updated_at timestamp(6) with time zone NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_barrio_reports_status_created ON barrio_reports (status, created_at);
CREATE INDEX IF NOT EXISTS ix_barrio_reports_category_status ON barrio_reports (category, status);

CREATE TABLE IF NOT EXISTS barrio_closure_claims (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id bigint NOT NULL,
  photo_path varchar(255) NOT NULL,
  comment varchar(500) NULL,
  status varchar(20) NOT NULL DEFAULT 'PENDING_REVIEW',
  created_at timestamp(6) with time zone NOT NULL,
  reviewed_at timestamp(6) with time zone NULL
);

CREATE INDEX IF NOT EXISTS ix_barrio_closure_claims_status ON barrio_closure_claims (status, created_at);
CREATE INDEX IF NOT EXISTS ix_barrio_closure_claims_report ON barrio_closure_claims (report_id);

CREATE TABLE IF NOT EXISTS barrio_wa_drafts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone varchar(30) NOT NULL,
  category varchar(16) NULL,
  photo_path varchar(255) NULL,
  lat double precision NULL,
  lng double precision NULL,
  updated_at timestamp(6) with time zone NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_barrio_wa_drafts_phone ON barrio_wa_drafts (phone);
