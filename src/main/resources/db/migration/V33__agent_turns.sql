-- Core Fase 3, pieza 3 (contrato CORE_FASE3_CONTRATO.md, 2026-10-06): memoria de las llamadas al
-- LLM. Cada turno del agente, cada clasificación de intake y cada saludo queda como una fila con
-- su veredicto (outcome) y los guards deterministas que se activaron — antes la decisión
-- "LLM vs heurística" solo vivía en líneas de log, y un mes de turnos cayendo a fallback pasó
-- inadvertido (parser de OpenAI roto, fix 2c90198). Mismo criterio que V19/V24/V25/V28/V29: tabla
-- nueva, CREATE ... IF NOT EXISTS (idempotente por el incidente de V11), sin JSONB (dev/test corre
-- H2 en modo PostgreSQL). En dev/test flyway está OFF y ddl-auto cubre la entidad AgentTurn — esta
-- migración no corre ahí pero se mantiene sincronizada con ella.
--
-- Sin FK a leads a propósito: los leads de prueba se borran a mano y el jar anterior no sabe de
-- esta tabla (rollback-safe). lead_id es null para un intake sin lead (POST /api/intake, o la
-- clasificación previa a crear el lead); NUNCA va acá el id de un provider_lead (un técnico).
--
-- user_content/raw_output contienen lo mismo que lead_messages: entran en el mismo pg_dump y se
-- limpian a mano junto con el lead. Sin retención automática en esta fase.

CREATE TABLE IF NOT EXISTS agent_turns (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lead_id bigint NULL,
  kind varchar(16) NOT NULL,
  provider varchar(32) NOT NULL,
  model varchar(80) NULL,
  prompt_version varchar(64) NOT NULL,
  user_content varchar(16000) NOT NULL,
  raw_output varchar(16000) NULL,
  latency_ms integer NOT NULL,
  outcome varchar(40) NOT NULL,
  guards varchar(400) NOT NULL DEFAULT '',
  created_at timestamp(6) with time zone NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_agent_turns_lead_created ON agent_turns (lead_id, created_at);
CREATE INDEX IF NOT EXISTS ix_agent_turns_created ON agent_turns (created_at);
